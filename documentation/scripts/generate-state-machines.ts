import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/**
 * The event status machine as a PlantUML state diagram, generated from the TRANSITIONS table in
 * planning-core's event module (F1), so the picture cannot drift from the rule.
 *
 *   npm run diagrams:states          rewrite documentation/architecture/domain/event-status.puml
 *   npm run diagrams:states:check    fail when the committed file differs from the code (CI)
 *
 * The other state diagrams in that folder (booking, hold, registration) are written by hand from
 * the repository functions that apply them; their sources are named in each file.
 */

export interface Edge {
  from: string;
  to: string;
  actions: string[];
}

const REPO = fileURLToPath(new URL("../../", import.meta.url));
const SOURCE = "backend/services/planning-core/src/modules/event/domain/statusMachine.ts";
const OUTPUT = "documentation/architecture/domain/event-status.puml";
const ENTRY = /^\s+([A-Z_]+): \{\s*from: \[([^\]]*)\],\s*to: "([A-Z_]+)",?\s*\},?$/gm;

/** Reads the TRANSITIONS table out of statusMachine.ts, one edge per (from, to) pair. */
export function readEdges(source: string): Edge[] {
  const table = /const TRANSITIONS[^=]*=\s*\{([\s\S]*?)\n\};/.exec(source);
  if (!table) throw new Error("TRANSITIONS table not found in statusMachine.ts");
  const edges = new Map<string, Edge>();
  for (const match of table[1]!.matchAll(ENTRY)) {
    const [, action, fromList, to] = match;
    for (const from of [...fromList!.matchAll(/"([A-Z_]+)"/g)].map((m) => m[1]!)) {
      const id = `${from}>${to}`;
      const edge = edges.get(id) ?? { from, to: to!, actions: [] };
      edge.actions.push(action!);
      edges.set(id, edge);
    }
  }
  if (edges.size === 0) throw new Error("No transition could be read from statusMachine.ts");
  return [...edges.values()];
}

const title = (status: string) => status.toLowerCase().split("_").map((w) => w[0]!.toUpperCase() + w.slice(1)).join(" ");

export function renderEventStatus(edges: readonly Edge[]): string {
  const states = [...new Set(edges.flatMap((e) => [e.from, e.to]))];
  const lines = [
    "@startuml event-status",
    `' Generated by documentation/scripts/generate-state-machines.ts from ${SOURCE}. Do not edit by hand.`,
    "title Event status machine (F1): every transition is a row of TRANSITIONS, applied only by transitionEvent",
    "hide empty description",
    "skinparam shadowing false",
    "",
    ...states.map((s) => `state "${title(s)}" as ${s}`),
    "",
    "[*] --> DRAFT : a request is started",
    ...edges.map((e) => `${e.from} --> ${e.to} : ${e.actions.join(" / ")}`),
    "CANCELLED --> [*]",
    "COMPLETED --> [*]",
    "REJECTED --> [*]",
    "",
    "@enduml",
    "",
  ];
  return lines.join("\n");
}

function main(): void {
  const content = renderEventStatus(readEdges(readFileSync(join(REPO, SOURCE), "utf8")));
  const path = join(REPO, OUTPUT);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (process.argv.includes("--check")) {
    if (current !== content) {
      console.error(`${OUTPUT} does not match ${SOURCE}.\nRun: npm run diagrams:states, then commit it and re-render the image.`);
      process.exit(1);
    }
    console.log("The event status diagram matches the status machine.");
  } else if (current !== content) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${OUTPUT}`);
  }
}

const isMain = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) main();
