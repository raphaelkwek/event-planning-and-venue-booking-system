/**
 * EN-22 — renders the traceability matrix (traceability-matrix.ts) as Markdown and HTML.
 * Kept apart from the generator so neither file grows past what a reviewer can read.
 */
import type { CriterionEntry, Matrix, StorySummary, TestEntry } from "./traceability-matrix.ts";

const RESULT_LABEL: Record<TestEntry["result"], string> = { pass: "pass", fail: "FAIL", skipped: "skipped", "not found": "NOT FOUND" };

const md = (text: string) => text.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const esc = (text: string) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const cardList = (test: TestEntry) => test.cards.map((card) => `${card.id}: ${card.status}`).join("; ");
const resultText = (test: TestEntry) => RESULT_LABEL[test.result] + (test.result === "not found" || test.note.startsWith("manual") ? ` (${test.note})` : "");

const HEADER = ["Story", "ACs", "Covered", "With failures", "No test", "Unverified", "Names not found"];
const summaryCells = (s: StorySummary) => [s.story, s.criteria, s.covered, s.failing, s.noTest, s.unverified, s.notFound].map(String);

function table(head: string[], rows: string[][]): string {
  return [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((row) => `| ${row.join(" | ")} |`)].join("\n");
}

function inputsLine(matrix: Matrix): string {
  return matrix.resultFiles.length === 0
    ? "**No test report was found**, so every test below is reported as not found. Pass the vitest or Playwright JSON with `--results`."
    : `Read ${matrix.testsWithResults} test results from ${matrix.resultFiles.length} report file(s).`;
}

function totalsLine(matrix: Matrix): string {
  const t = matrix.totals;
  const odd = matrix.stories.flatMap(({ summary }) => summary.nonStandardCards);
  const cards = odd.length > 0 ? ` Warning: ${odd.length} cards have a Status other than Pass, Fail, Not Executed or Blocked (first: ${odd.slice(0, 5).join(", ")}).` : "";
  return `${matrix.stories.length} stories, ${t.criteria} acceptance criteria: ${t.covered} covered, ${t.failing} with a failing test, ${t.noTest} with no test, ${t.unverified} with tests but no pass, ${t.notFound} test names that do not exist.${cards}`;
}

function criterionRows(entry: CriterionEntry): string[][] {
  if (entry.tests.length === 0) return [[md(entry.criterion), "_no test_", "NO TEST", ""]];
  return entry.tests.map((test, i) => [
    i === 0 ? md(entry.criterion) : "",
    `\`${md(test.file)}\` › ${md(test.name)}`,
    resultText(test),
    md(cardList(test)),
  ]);
}

/** Every criterion with no test and every test name that does not exist, for the people who fix them. */
export function mismatches(matrix: Matrix): { story: string; kind: "no test" | "not found"; criterion: string; detail: string }[] {
  return matrix.stories.flatMap(({ story, criteria }) =>
    criteria.flatMap((entry) => [
      ...(entry.tests.length === 0 ? [{ story, kind: "no test" as const, criterion: entry.criterion, detail: "" }] : []),
      ...entry.tests
        .filter((test) => test.result === "not found")
        .map((test) => ({ story, kind: "not found" as const, criterion: entry.criterion, detail: `${test.sprint} row ${test.row}: ${test.file} › ${test.name} (${test.note})` })),
    ]),
  );
}

function mismatchSection(matrix: Matrix): string {
  const list = mismatches(matrix);
  if (list.length === 0) return "No mismatches.";
  return table(["Story", "Problem", "Criterion", "Test"], list.map((m) => [m.story, m.kind === "no test" ? "no test" : "name not found", md(m.criterion.slice(0, 120)), md(m.detail)]));
}

export function renderMarkdown(matrix: Matrix): string {
  const detail = matrix.stories.map(({ story, criteria, cards }) => {
    const cardsLine = cards.length === 0 ? "No functional cards." : `Cards: ${cards.map((card) => `${card.id} (${card.status})`).join(", ")}`;
    return [`## ${story}`, "", table(["Acceptance criterion", "Test", "Last result", "Cards"], criteria.flatMap(criterionRows)), "", cardsLine].join("\n");
  });
  return [
    "# Traceability matrix",
    "",
    "Story, acceptance criterion, test, last result. Generated by `documentation/scripts/traceability-matrix.ts`.",
    "",
    inputsLine(matrix),
    "",
    totalsLine(matrix),
    "",
    ...detail.flatMap((section) => [section, ""]),
    "## Mismatches",
    "",
    mismatchSection(matrix),
    "",
    "## Summary per story",
    "",
    table(HEADER, matrix.stories.map(({ summary }) => summaryCells(summary))),
    "",
  ].join("\n");
}

/** The short form for the job summary: the totals, the mismatches and the per-story summary. */
export function renderSummary(matrix: Matrix): string {
  return [
    "## Traceability",
    "",
    inputsLine(matrix),
    "",
    totalsLine(matrix),
    "",
    "Mismatches are warnings, not failures. The full matrix is the `traceability-matrix` artifact.",
    "",
    "<details><summary>Mismatches</summary>",
    "",
    mismatchSection(matrix),
    "",
    "</details>",
    "",
    "### Summary per story",
    "",
    table(HEADER, matrix.stories.map(({ summary }) => summaryCells(summary))),
    "",
  ].join("\n");
}

const STYLE = `body{font:14px/1.45 system-ui,sans-serif;margin:2rem auto;max-width:1200px;padding:0 1rem;color:#172b4d}
table{border-collapse:collapse;width:100%;margin:.5rem 0 1rem}th,td{border:1px solid #dfe1e6;padding:4px 8px;text-align:left;vertical-align:top}
th{background:#f4f5f7}code{font-size:12px}.pass{color:#216e4e}.fail,.notfound,.notest{color:#ae2e24;font-weight:600}.skipped{color:#7f5f01}`;

const cls = (text: string) => text.toLowerCase().replace(/[^a-z]/g, "");

function htmlTable(head: string[], rows: string[][], classCol?: number): string {
  const body = rows.map((row) => `<tr>${row.map((cell, i) => `<td${classCol === i ? ` class="${cls(cell.split(" ")[0] ?? "")}"` : ""}>${cell}</td>`).join("")}</tr>`).join("\n");
  return `<table><thead><tr>${head.map((h) => `<th>${esc(h)}</th>`).join("")}</tr></thead><tbody>\n${body}\n</tbody></table>`;
}

export function renderHtml(matrix: Matrix): string {
  const sections = matrix.stories.map(({ story, criteria, cards }) => {
    const rows = criteria.flatMap((entry) =>
      entry.tests.length === 0
        ? [[esc(entry.criterion), "<em>no test</em>", "NO TEST", ""]]
        : entry.tests.map((test, i) => [i === 0 ? esc(entry.criterion) : "", `<code>${esc(test.file)}</code> &rsaquo; ${esc(test.name)}`, esc(resultText(test)), esc(cardList(test))]),
    );
    const cardsLine = cards.length === 0 ? "No functional cards." : `Cards: ${esc(cards.map((card) => `${card.id} (${card.status})`).join(", "))}`;
    return `<h2 id="${esc(story)}">${esc(story)}</h2>\n${htmlTable(["Acceptance criterion", "Test", "Last result", "Cards"], rows, 2)}\n<p>${cardsLine}</p>`;
  });
  const list = mismatches(matrix);
  const mismatchRows = list.map((m) => [esc(m.story), m.kind === "no test" ? "no test" : "name not found", esc(m.criterion.slice(0, 160)), esc(m.detail)]);
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Traceability matrix</title><style>${STYLE}</style></head>
<body>
<h1>Traceability matrix</h1>
<p>${esc(inputsLine(matrix))}</p>
<p>${esc(totalsLine(matrix))}</p>
${sections.join("\n")}
<h2>Mismatches</h2>
${list.length === 0 ? "<p>No mismatches.</p>" : htmlTable(["Story", "Problem", "Criterion", "Test"], mismatchRows)}
<h2>Summary per story</h2>
${htmlTable(HEADER, matrix.stories.map(({ summary }) => summaryCells(summary).map(esc)))}
</body></html>
`;
}
